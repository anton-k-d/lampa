import { test } from 'node:test';
import assert from 'node:assert/strict';
import { mkdtempSync, rmSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { openConfigDatabase } from '../../src/config/database.mjs';
import { createConfigRepository } from '../../src/config/repository.mjs';
import { createConfigService } from '../../src/config/service.mjs';
import { createRuntimeStore } from '../../src/runtime/store.mjs';
import { createHomeServer } from '../../src/http/server.mjs';

const global = values => ({ schemaVersion: 1, scope: 'global', values });

test('HTTP configuration supports revision, retry, conflict, rollback and effective cache', async t => {
  const dir = mkdtempSync(join(tmpdir(), 'lampa-http-'));
  const db = openConfigDatabase(join(dir, 'config.db'));
  const repository = createConfigRepository(db);
  const runtimeStore = createRuntimeStore(db);
  const service = createConfigService({ repository, policy: runtimeStore.context });
  const server = createHomeServer({ repository, service, runtimeStore, allowedHosts: ['127.0.0.1'] });
  await new Promise(resolve => server.listen(0, '127.0.0.1', resolve));
  t.after(async () => { await new Promise(resolve => server.close(resolve)); db.close(); rmSync(dir, { recursive: true, force: true }); });
  const base = `http://127.0.0.1:${server.address().port}`;
  const read = path => fetch(base + path);
  const put = (document, revision, key) => fetch(base + '/v1/admin/config/global', { method:'PUT', headers:{'content-type':'application/json','if-match':`"r-${revision}"`,'idempotency-key':key}, body:JSON.stringify(document) });
  let response = await read('/v1/admin/config/global');
  assert.deepEqual(await response.json(), { document: global({}), revision: 0 });
  response = await put(global({ui:{theme:'dark'}}), 0, 'one');
  assert.equal(response.status, 200);
  const first = await response.json();
  response = await put(global({ui:{theme:'dark'}}), 0, 'one');
  assert.deepEqual(await response.json(), first);
  assert.equal((await put(global({}), 0, 'two')).status, 412);
  response = await fetch(base + '/v1/admin/config/validate', {method:'POST',headers:{'content-type':'application/json'},body:JSON.stringify({scopeKey:'device:tv',document:{schemaVersion:1,scope:'device',deviceId:'tv',values:{ui:{density:'compact'}}}})});
  assert.deepEqual(await response.json(),{valid:true,issues:[]});
  response = await fetch(base + '/v1/admin/devices/tv/config', {method:'PUT',headers:{'content-type':'application/json','if-match':'"r-0"','idempotency-key':'device'},body:JSON.stringify({schemaVersion:1,scope:'device',deviceId:'tv',values:{ui:{density:'compact'}}})});
  assert.equal(response.status,200);
  response = await read('/v1/devices/tv/config');
  const effective = await response.json();
  assert.equal(effective.values.ui.theme, 'dark'); assert.equal(effective.values.ui.density,'compact'); assert.ok(effective.revisions.device > 0);
  assert.equal((await fetch(base + '/v1/devices/tv/config', {headers:{'if-none-match':response.headers.get('etag')}})).status, 304);
  response = await fetch(base + '/v1/admin/config/rollback', {method:'POST',headers:{'content-type':'application/json','if-match':`"r-${first.revision}"`,'idempotency-key':'rollback'},body:JSON.stringify({scopeKey:'global',targetRevision:first.revision})});
  assert.equal(response.status, 200);
});

test('HTTP rejects unsafe requests and protects static files', async t => {
  const { mkdirSync, writeFileSync, symlinkSync } = await import('node:fs');
  const { validateLiteValues } = await import('../../src/http/lite-policy.mjs');
  const dir = mkdtempSync(join(tmpdir(), 'lampa-http-'));
  const root = join(dir,'admin'); mkdirSync(root); writeFileSync(join(root,'index.html'),'admin');
  writeFileSync(join(dir,'outside.txt'),'secret'); symlinkSync(join(dir,'outside.txt'),join(root,'link'));
  const db = openConfigDatabase(join(dir,'db'));
  const repository = createConfigRepository(db), runtimeStore = createRuntimeStore(db);
  const service = createConfigService({repository,policy:runtimeStore.context,additionalValidator:validateLiteValues});
  const server = createHomeServer({repository,service,runtimeStore,adminRoot:root,allowedHosts:['127.0.0.1']});
  await new Promise(resolve => server.listen(0,'127.0.0.1',resolve));
  t.after(async () => { await new Promise(resolve => server.close(resolve)); db.close(); rmSync(dir,{recursive:true,force:true}); });
  const base = `http://127.0.0.1:${server.address().port}`;
  const redirect = await fetch(base+'/', {redirect:'manual'});
  assert.equal(redirect.status,302); assert.equal(redirect.headers.get('location'),'/admin/');
  assert.equal(await (await fetch(base+'/admin/')).text(),'admin');
  assert.equal((await fetch(base+'/admin/link')).status,404);
  assert.equal((await fetch(base+'/admin/%2e%2e%2foutside.txt')).status,404);
  assert.equal((await fetch(base+'/v1/admin/config/global',{method:'PUT',headers:{origin:'http://evil.example','if-match':'"r-0"','idempotency-key':'a','content-type':'application/json'},body:'{}'})).status,403);
  assert.equal((await fetch(base+'/v1/admin/config/global',{method:'PUT',headers:{'if-match':'"r-0"','idempotency-key':'a','content-type':'application/json'},body:'x'.repeat(262145)})).status,413);
  assert.equal((await fetch(base+'/v1/admin/config/validate',{method:'POST',headers:{'content-type':'text/plain'},body:'{}'})).status,400);
  assert.equal((await fetch(base+'/no-such-route',{method:'POST'})).status,404);
  const response = await fetch(base+'/v1/admin/config/global',{method:'PUT',headers:{'if-match':'"r-0"','idempotency-key':'bad','content-type':'application/json'},body:JSON.stringify(global({features:{sync:true},'password-123':'https://private.example'}))});
  const text = await response.text(); assert.equal(response.status,422); assert.equal(text.includes('password-123'),false); assert.equal(text.includes('private.example'),false);
  const unsupported = await fetch(base+'/v1/admin/config/global',{method:'PUT',headers:{'if-match':'"r-0"','idempotency-key':'unsupported','content-type':'application/json'},body:JSON.stringify(global({features:{sync:true}}))});
  assert.equal(unsupported.status,422); assert.equal((await unsupported.json()).code,'UNSUPPORTED_CAPABILITY');
});

test('unsupported archived configuration cannot be rolled back or exposed as effective', async t => {
  const { validateLiteValues } = await import('../../src/http/lite-policy.mjs');
  const dir = mkdtempSync(join(tmpdir(),'lampa-http-'));
  const path = join(dir,'db');
  const db = openConfigDatabase(path), repository = createConfigRepository(db), runtimeStore = createRuntimeStore(db);
  const legacy = createConfigService({repository,policy:runtimeStore.context});
  const input = (document, expectedRevision, mutationId) => ({scopeKey:'global',document,expectedRevision,mutationId,actorId:'legacy',reason:null});
  const old = legacy.publish(input(global({features:{sync:true}}),0,'old'));
  const current = legacy.publish(input(global({}),old.revision,'current'));
  const service = createConfigService({repository,policy:runtimeStore.context,additionalValidator:validateLiteValues});
  const server = createHomeServer({repository,service,runtimeStore,allowedHosts:['127.0.0.1']});
  await new Promise(resolve => server.listen(0,'127.0.0.1',resolve));
  const base = `http://127.0.0.1:${server.address().port}`;
  let response = await fetch(base+'/v1/admin/config/rollback',{method:'POST',headers:{'content-type':'application/json','if-match':`"r-${current.revision}"`,'idempotency-key':'rb'},body:JSON.stringify({scopeKey:'global',targetRevision:old.revision})});
  assert.equal(response.status,422); assert.equal((await response.json()).code,'UNSUPPORTED_CAPABILITY');
  legacy.publish(input(global({features:{sync:true}}),current.revision,'legacy-again'));
  response = await fetch(base+'/v1/devices/tv/config'); assert.equal(response.status,422); assert.equal((await response.json()).code,'UNSUPPORTED_CAPABILITY');
  response = await fetch(base+'/v1/admin/config/global'); assert.equal((await response.json()).document.values.features.sync,true);
  await new Promise(resolve => server.close(resolve)); db.close();
  const reopened = openConfigDatabase(path); assert.equal(createConfigRepository(reopened).getHead('global').document.values.features.sync,true); reopened.close();
  rmSync(dir,{recursive:true,force:true});
});
